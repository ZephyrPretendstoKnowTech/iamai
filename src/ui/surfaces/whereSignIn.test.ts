test('the spec’s three policies close the doors, and the objects they reference are drawn above the policies', () => {
  assert.deepEqual(WHERE_SIGN_IN.map((id) => groupOf(id)?.key), ['remaining-doors', 'remaining-doors', 'remaining-doors'])
  assert.deepEqual(PREPARE_OBJECTS.map((id) => groupOf(id)?.key), ['prepare', 'prepare'])
  // The spec's six steps are five now: the objects drawn above the policies
  // that reference them, and the countries location inside its policy.
  assert.deepEqual([...PREPARE_OBJECTS, ...WHERE_SIGN_IN].sort(), ['s-goal-geo-restriction', 's-goal-service-accounts-trusted-network', 's-goal-workload-identity-block', 's-prereq-service-accounts-group', 's-prereq-trusted-location'])
})

// Left at No, a network condition is not configured and the policy reaches every
// sign-in: for a block that is a lockout. Every network policy of the group says
// Configure: Yes, in its create, its correction and the reviewer's transcription.
test('every network policy sets its condition through Configure: Yes, in create and in correct', () => {
  const cases: [string, string, string, string][] = [
    ['geo-restriction', 's-goal-geo-restriction', 'entra.create', 'entra.correct-conditions'],
    ['service-accounts-trusted-network', 's-goal-service-accounts-trusted-network', 'entra.create', 'entra.correct.network'],
    ['workload-identity-block', 's-goal-workload-identity-block', 'entra.policy.create', 'entra.correct.policy.location-boundary'],
  ]
  for (const [contentId, stepId, create, correct] of cases) {
    assert.match(blockText(stepId, create), /set \*\*Configure\*\* to \*\*Yes\*\*/, `${stepId}: create`)
    assert.match(blockText(stepId, correct), /set \*\*Configure\*\* to \*\*Yes\*\*/, `${stepId}: correct`)
    assert.match(allText(contentId), /Configure: Yes, then Include: Any network or location/, contentId)
  }
  assert.match(blockText('s-goal-geo-restriction', 'entra.create'), /Left at \*\*No\*\* the network condition is not configured/)
  assert.match(blockText('s-goal-service-accounts-trusted-network', 'entra.create'), /Left at \*\*No\*\* the network condition is not configured/)
})

test('T5: the step names every step that waits on it, which the board proves is four', () => {
  const waits = String((stepById['s-prereq-trusted-location'] as unknown as { more?: { waits?: string } }).more?.waits ?? '')
  // The demo's board holds exactly these four waiting on this object.
  const waiting = ['s-shared-devices', 's-goal-register-info-protected', 's-goal-require-managed-device', 's-goal-service-accounts-trusted-network']
  const bodies = bodiesOf('demo')
  for (const id of waiting) {
    const tiles = JSON.stringify(bodies.get(id)!.allTiles)
    assert.match(tiles, /Define the Trusted Network/, `${id}: the board does not show it waiting on the trusted network`)
    assert.ok(waits.includes(bodies.get(id)!.title), `${waits}\n  does not name ${bodies.get(id)!.title}`)
  }
})
